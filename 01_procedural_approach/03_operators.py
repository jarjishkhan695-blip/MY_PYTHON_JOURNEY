"""
Operators in Python

Operators are used to perform operations on values.
"""

a = 10
b = 3

# Arithmetic operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)

# Comparison operators
print("a > b:", a > b)
print("a == b:", a == b)
print("a != b:", a != b)

# Logical operators
is_student = True
has_id_card = False

print("AND:", is_student and has_id_card)
print("OR:", is_student or has_id_card)
print("NOT:", not is_student)
